type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const defaultValue: I18nContextValue = {
  language: "zh",
  setLanguage: () => undefined,
  t: (key, values) => format(messages.zh[key] ?? key, values),
};

const I18nContext = createContext<I18nContextValue>(defaultValue);

function format(message: string, values?: Record<string, string | number>): string {
  if (!values) return message;
  return Object.entries(values).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), message);
}

export function LanguageProvider({ children, initialLanguage }: { children: ReactNode; initialLanguage?: Language }) {
  const [language, setLanguageState] = useState<Language>(() => initialLanguage ?? (window.localStorage?.getItem("mailops_language") === "en" ? "en" : "zh"));
  const setLanguage = (next: Language) => {
    window.localStorage?.setItem("mailops_language", next);
    setLanguageState(next);
  };
  useEffect(() => { document.documentElement.lang = language === "zh" ? "zh-CN" : "en"; }, [language]);
  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => format(messages[language][key] ?? messages.en[key] ?? key, values),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
